#!/usr/bin/env node
/**
 * Emit a typed command map from a region's GET /commands/schema (+ optional /commands/meta).
 *
 * Usage: nexus-commands-codegen --region https://region.example [--out nexus-commands.d.ts]
 */
import { writeFileSync } from 'node:fs';

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  if (i >= 0 && process.argv[i + 1]) return process.argv[i + 1];
  return fallback;
}

const region = arg('--region', process.env.NEXUS_REGION_URL);
const out = arg('--out', 'nexus-commands.generated.d.ts');

if (!region) {
  console.error('Usage: nexus-commands-codegen --region <url> [--out file.d.ts]');
  process.exit(1);
}

const base = region.replace(/\/$/, '');

async function main() {
  const [schemaRes, metaRes] = await Promise.all([
    fetch(`${base}/commands/schema`),
    fetch(`${base}/commands/meta`).catch(() => null),
  ]);
  if (!schemaRes.ok) {
    throw new Error(`schema fetch failed: ${schemaRes.status}`);
  }
  const schema = await schemaRes.json();
  let meta = { catalogVersion: 'unknown', catalogFingerprint: 'unknown' };
  if (metaRes && metaRes.ok) {
    meta = await metaRes.json();
  }

  const commands = schema.commands || schema.paths || schema;
  const names = Array.isArray(commands)
    ? commands.map((c) => (typeof c === 'string' ? c : c.name)).filter(Boolean)
    : Object.keys(commands || {});

  const lines = [
    '/* eslint-disable */',
    `/** Generated by @nexus/commands-client codegen against ${base}`,
    ` *  catalogVersion: ${meta.catalogVersion}`,
    ` *  catalogFingerprint: ${meta.catalogFingerprint}`,
    ` *  generatedAt: ${new Date().toISOString()}`,
    ' */',
    'export type NexusCommandName =',
    ...names.map((n, i) => `  | '${n}'${i === names.length - 1 ? ';' : ''}`),
    '',
    'export type NexusCommandMap = {',
    ...names.map((n) => `  '${n}': { payload: Record<string, unknown>; response: unknown };`),
    '};',
    '',
  ];

  writeFileSync(out, lines.join('\n'));
  console.log(`Wrote ${out} (${names.length} commands)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
